import mongoose from "mongoose";

const knowledgeItemSchema = new mongoose.Schema({
  title: {
    type: String,
    required: true,
    trim: true,
  },
  description: {
    type: String,
    required: true,
    trim: true,
  },
  category: {
    type: String,
    required: true,
    trim: true,
  },
  createdBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: "User",
    required: true,
  },
  updatedBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: "User",
  },
  embedding: {
    type: [Number], // store vector embedding
    default: [],
  },
},
  { timestamps: true }
);

export default mongoose.model("KnowledgeItem", knowledgeItemSchema);
